function mostrarECA() {
    document.getElementById("conteudo").innerHTML = `
        <h2>
            O ECA é a legislação brasileira que garante proteção integral às
            crianças e adolescentes, considerando-os pessoas em desenvolvimento com direitos próprios e
            prioridade absoluta na sociedade.
        </h2>

        <p><span>Entre outros, o ECA assegura:</span></p>
        <p>- Direito à vida, à saúde e à dignidade;</p>
        <p>- Direito à educação, cultura, esporte e lazer;</p>
        <p>- Proteção contra negligência, discriminação, violência e exploração;</p>
        <p>- Convivência familiar e comunitária;</p>
        <p>- Prioridade em políticas públicas e serviços essenciais.</p>
        <hr>

        <p><span>Deveres da família, da sociedade e do Estado:</span></p>
        <p>- Garantir o desenvolvimento físico, mental, moral e social;</p>
        <p>- Proteger contra qualquer forma de abuso ou violação;</p>
        <p>- Assegurar acesso à escola e à saúde;</p>
        <p>- Comunicar situações de risco aos órgãos competentes.</p>
        <hr>

        <p><span>O Conselho Tutelar é um órgão previsto no ECA com estas funções principais:</span></p>
        <p>- Receber denúncias de violação de direitos;</p>
        <p>- Atender e orientar crianças, adolescentes, responsáveis e a comunidade;</p>
        <p>- Aplicar medidas de proteção quando direitos são violados;</p>
        <p>- Encaminhar casos para a rede de proteção social;</p>
        <p>- Acompanhar famílias em situação de vulnerabilidade.</p>
        <hr>

        <p><span>Quando devo acionar o Conselho Tutelar?</span></p>
        <p>- Quando uma criança ou adolescente sofre violência física ou psicológica;</p>
        <p>- Quando há negligência, abandono ou exploração;</p>
        <p>- Quando direitos educacionais ou de saúde não são assegurados;</p>
        <p>- Quando a família precisa de orientação ou apoio institucional.</p>

        <p class="fonte">
        Fonte: Estatuto da Criança e do Adolescente - Lei nº 8.069/1990
        </p>
    `;
}

